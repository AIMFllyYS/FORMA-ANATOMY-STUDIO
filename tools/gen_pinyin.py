#!/usr/bin/env python3
"""Generate compact pinyin tables from local knowledge strings. Not medical review."""
from __future__ import annotations
import json, re
from pathlib import Path
from pypinyin import Style, lazy_pinyin

ROOT = Path(__file__).resolve().parents[1]
HAN = re.compile(r'[\u4e00-\u9fff]+')
# Anatomy-specific readings pypinyin commonly misses.
PHRASE_FIX = {
    '切迹': 'qiē jì',
    '切迹或孔': 'qiē jì huò kǒng',
    '附着': 'fù zhuó',
    '走行': 'zǒu xíng',
}
CHAR_FIX = {
    '切': 'qiē',   # 切迹
    '椎': 'zhuī',  # vertebra, not chuí
    '肋': 'lèi',   # rib, not lē
    '长': 'cháng', # longus / long muscles
    '骰': 'shǎi',  # cuboid
    '踇': 'mǔ',    # hallux; same reading as 拇, distinct character
}


def py_of(text: str) -> str:
    if text in PHRASE_FIX:
        return PHRASE_FIX[text]
    parts = []
    last = 0
    for m in HAN.finditer(text):
        parts.append(text[last:m.start()])
        chunk = m.group(0)
        if chunk in PHRASE_FIX:
            parts.append(PHRASE_FIX[chunk])
        else:
            syllables = []
            i = 0
            while i < len(chunk):
                hit = None
                for n in range(min(6, len(chunk) - i), 1, -1):
                    sub = chunk[i:i + n]
                    if sub in PHRASE_FIX:
                        hit = PHRASE_FIX[sub]
                        i += n
                        break
                if hit:
                    syllables.append(hit)
                else:
                    ch = chunk[i]
                    syllables.append(CHAR_FIX.get(ch) or lazy_pinyin(ch, style=Style.TONE)[0])
                    i += 1
            parts.append(' '.join(syllables))
        last = m.end()
    parts.append(text[last:])
    out = re.sub(r'\s*([/·,，、])\s*', r' \1 ', ''.join(parts))
    out = re.sub(r'([āáǎàēéěèīíǐìōóǒòūúǔùǖǘǚǜüa-z])(\d)', r'\1 \2', out)
    out = re.sub(r'(\d)(?=[āáǎàēéěèīíǐìōóǒòūúǔùǖǘǚǜüa-z])', r'\1 ', out)
    return re.sub(r' {2,}', ' ', out).strip()


def collect() -> tuple[set[str], set[str]]:
    phrases: set[str] = set()
    chars: set[str] = set()
    data = json.loads((ROOT / 'web' / 'knowledge.json').read_text(encoding='utf-8'))
    js = (ROOT / 'web' / 'knowledge.js').read_text(encoding='utf-8')
    core = (ROOT / 'web' / 'core.js').read_text(encoding='utf-8')

    def add(s: str | None):
        if not s:
            return
        for m in HAN.findall(s):
            phrases.add(m)
            chars.update(m)
        if HAN.search(s):
            phrases.add(s)

    for c in data['cards']:
        add(c.get('zh'))
        for lm in c.get('landmarks') or []:
            add(lm.get('zh'))
    for m in re.findall(r"\bzh:'([^']+)'", js):
        add(m)
    for m in re.findall(r"\b(?:bone|soft)\('([^']+)'", js):
        add(m)
    for m in re.findall(r"\['[^']+','([^']*[\u4e00-\u9fff][^']*)'\]", js):
        add(m)
    for m in re.findall(r"name:'([^']*[\u4e00-\u9fff][^']*)'", core):
        add(m)
    for extra in ('左侧', '右侧', '骨骼', '肌肉', '神经', '关节', '韧带', '头颈', '脊柱', '胸腹', '上肢', '骨盆', '下肢'):
        add(extra)
    # Nomenclature layer (Task 9): every mapped zh name and its functional groups
    # so pinyin search covers muscles/organs added beyond the knowledge cards.
    nom_path = ROOT / 'web' / 'nomenclature.json'
    if nom_path.exists():
        nom = json.loads(nom_path.read_text(encoding='utf-8'))
        for rec in nom.get('records', {}).values():
            add(rec.get('zh'))
            add(rec.get('group'))
            add(rec.get('subgroup'))
    return phrases, chars


def emit_js(phrases: set[str], chars: set[str]) -> str:
    phrase_map = {p: py_of(p) for p in phrases if len(re.sub(r'[^\u4e00-\u9fff]', '', p)) >= 2}
    phrase_map.update(PHRASE_FIX)
    chars.update(CHAR_FIX)
    char_map = {ch: CHAR_FIX.get(ch) or lazy_pinyin(ch, style=Style.TONE)[0] for ch in sorted(chars)}
    payload = json.dumps({'phrase': phrase_map, 'char': char_map}, ensure_ascii=False, separators=(',', ':'))
    return '/* Generated by tools/gen_pinyin.py. Learning aid; not a phonetic authority. */\nwindow.FormaPinyin=' + payload + ';\n'


def main():
    phrases, chars = collect()
    out = ROOT / 'web' / 'pinyin-data.js'
    js = emit_js(phrases, chars)
    # Sanity samples
    samples = ['肱骨', '额骨', '切迹', '眶上切迹/孔', '左侧', '附着', '走行', '上关节突']
    report = {s: py_of(s) for s in samples}
    print('phrases', len(phrases), 'chars', len(chars), 'js_bytes', len(js.encode()))
    print('samples', report)
    # Only print; caller decides whether to embed.
    out.write_text(js, encoding='utf-8')
    print('wrote', out)


if __name__ == '__main__':
    main()
